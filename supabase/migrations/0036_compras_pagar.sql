-- ------------------------------------------------------------
-- RECEBER MERCADORIA SEM VER PREÇO (decisão do Bruno, 01/10: a Bia recebe)
--
-- A produção recebe o pedido na porta da cozinha, mas não lê
-- purchase_orders (tem preço). Esta função entrega SÓ o que a porta
-- precisa: fornecedor, data, itens e quantidades — nenhum valor.
-- O registro continua por compra_receber(), que já aceita a produção.
-- ------------------------------------------------------------
create or replace function public.compras_a_receber()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select case
    when public.papel() not in ('admin', 'compras', 'logistica', 'producao') then '[]'::jsonb
    else coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', po.id,
               'numero', po.numero,
               'forma', po.forma,
               'data_prevista', po.data_prevista,
               'fornecedor_nome', f.nome,
               'itens', (
                 select coalesce(jsonb_agg(jsonb_build_object(
                          'id', i.id,
                          'purchase_order_id', i.purchase_order_id,
                          'descricao', i.descricao,
                          'quantidade', i.quantidade,
                          'unidade', i.unidade,
                          'event_id', i.event_id,
                          'quantidade_recebida', i.quantidade_recebida
                        ) order by i.ordem, i.descricao), '[]'::jsonb)
                 from public.purchase_order_items i
                 where i.purchase_order_id = po.id)
             ) order by po.data_prevista nulls last, po.numero)
      from public.purchase_orders po
      left join public.fornecedores f on f.id = po.fornecedor_id
      where po.status = 'confirmado'
    ), '[]'::jsonb)
  end;
$$;

grant execute on function public.compras_a_receber() to authenticated;
