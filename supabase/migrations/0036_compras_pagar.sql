-- security_invoker: a view respeita a RLS de payables (só financeiro/admin)
create or replace view public.payables_abertos
with (security_invoker = true) as
  select p.*,
         (p.status = 'a_pagar' and p.vencimento < current_date) as atrasado,
         (p.vencimento - current_date)                          as dias_ate_vencer,
         f.nome                                                 as fornecedor_nome,
         po.numero                                              as pedido_numero,
         coalesce(exists (
           select 1 from public.purchase_order_items i
           where i.purchase_order_id = p.purchase_order_id
             and i.quantidade_recebida is not null
             and i.quantidade_recebida <> i.quantidade
         ), false)                                              as pedido_divergente,
         fr.nome                                                as freelancer_nome,
         e.nome                                                 as evento_nome
  from public.payables p
  left join public.fornecedores f     on f.id = p.fornecedor_id
  left join public.purchase_orders po on po.id = p.purchase_order_id
  left join public.freelancers fr     on fr.id = p.freelancer_id
  left join public.events e           on e.id = p.event_id
  where p.status <> 'cancelado';

-- Resumo do pedido para COMPRAS: inclui quantas parcelas já foram pagas.
-- Compras não lê payables (é caixa da empresa); esta view mostra só a
-- contagem, por isso roda com o dono e filtra por pode_ver_compras().
create or replace view public.purchase_orders_resumo as
  select po.*,
         f.nome      as fornecedor_nome,
         f.telefone  as fornecedor_telefone,
         (select count(*) from public.purchase_order_items i where i.purchase_order_id = po.id)::int as itens_qtd,
         coalesce(exists (
           select 1 from public.purchase_order_items i
           where i.purchase_order_id = po.id
             and i.quantidade_recebida is not null
             and i.quantidade_recebida <> i.quantidade
         ), false)   as divergente,
         (select count(*) from public.payables p
           where p.purchase_order_id = po.id and p.status <> 'cancelado')::int as parcelas_total,
         (select count(*) from public.payables p
           where p.purchase_order_id = po.id and p.status = 'pago')::int as parcelas_pagas,
         coalesce((select sum(coalesce(p.valor_pago, p.valor)) from public.payables p
           where p.purchase_order_id = po.id and p.status = 'pago'), 0) as valor_pago
  from public.purchase_orders po
  join public.fornecedores f on f.id = po.fornecedor_id
  where public.pode_ver_compras();

-- ------------------------------------------------------------
-- 6. FUNÇÕES — a regra que mexe em dinheiro roda no banco
-- (mesma regra de src/engine/financeiro.ts: gerarParcelas, agruparDiarias)
-- ------------------------------------------------------------

/**
 * Confirma o pedido e gera as contas a pagar. Security definer porque
 * quem compra não escreve em payables — só por aqui.
 * Condição 'avista' → 1 parcela na data prevista; '14/28' → 2 parcelas,
 * a diferença de centavos vai na última.
 */
create or replace function public.compra_confirmar(p_pedido uuid)
returns int
language plpgsql
security definer
set search_path = public
as $$
declare
  v_po      public.purchase_orders%rowtype;
  v_total   numeric(12,2);
  v_dias    int[];
  v_n       int;
  v_cada    numeric(12,2);
  v_forn    text;
  v_evento  uuid;
  i         int;
begin
  if not public.pode_pedir_compra() then
    raise exception 'Só compras ou admin confirmam pedido.';
  end if;

  -- libera as travas de pedido (seção 6b) só dentro desta função
  perform set_config('pieggi.compra_fn', '1', true);

  select * into v_po from public.purchase_orders where id = p_pedido for update;
  if not found then raise exception 'Pedido não encontrado.'; end if;
  if v_po.status not in ('rascunho', 'enviado') then
    raise exception 'O pedido % está %, não dá para confirmar.', v_po.numero, v_po.status;
  end if;
  if v_po.data_prevista is null then
    raise exception 'Falta a data prevista (é dela que contam os vencimentos).';
  end if;
  if not exists (select 1 from public.purchase_order_items where purchase_order_id = p_pedido) then
    raise exception 'O pedido não tem itens.';
  end if;
  if exists (select 1 from public.purchase_order_items
             where purchase_order_id = p_pedido
               and (coalesce(preco_unitario, 0) <= 0 or coalesce(quantidade, 0) <= 0)) then
    raise exception 'Há item sem preço ou sem quantidade — complete antes de confirmar.';
  end if;

  select round(sum(quantidade * preco_unitario), 2) into v_total
    from public.purchase_order_items where purchase_order_id = p_pedido;

  -- um evento só? a conta a pagar já nasce ligada a ele
  select case when count(distinct event_id) = 1 and count(*) = count(event_id)
              then min(event_id::text)::uuid end
    into v_evento
    from public.purchase_order_items where purchase_order_id = p_pedido;

  if v_po.condicao_pagamento is null or v_po.condicao_pagamento = 'avista' then
    v_dias := array[0];
  else
    select array_agg(trim(x)::int order by ord) into v_dias
      from unnest(string_to_array(v_po.condicao_pagamento, '/')) with ordinality as t(x, ord)
     where trim(x) ~ '^\d+$';
    if v_dias is null then v_dias := array[0]; end if;
  end if;
  v_n := array_length(v_dias, 1);
  v_cada := trunc(v_total / v_n, 2);

  select nome into v_forn from public.fornecedores where id = v_po.fornecedor_id;

  for i in 1 .. v_n loop
    insert into public.payables
      (fornecedor_id, purchase_order_id, event_id, categoria, descricao, parcela, parcelas,
       valor, vencimento, forma_pagamento, created_by)
    values
      (v_po.fornecedor_id, v_po.id, v_evento, 'insumos',
       format('Pedido %s — %s', v_po.numero, v_forn), i, v_n,
       case when i = v_n then v_total - v_cada * (v_n - 1) else v_cada end,
       v_po.data_prevista + v_dias[i], v_po.forma_pagamento, auth.uid());
  end loop;

  update public.purchase_orders
     set status = 'confirmado', confirmado_em = now(), valor_total = v_total
   where id = p_pedido;

  perform set_config('pieggi.compra_fn', '', true);
  return v_n;
end;
$$;

/** Cancela o pedido; se já confirmado, cancela as parcelas ainda não pagas. */
create or replace function public.compra_cancelar(p_pedido uuid)
returns int
language plpgsql
security definer
set search_path = public
as $$
declare
  v_status text;
  v_n      int;
begin
  if not public.pode_pedir_compra() then
    raise exception 'Só compras ou admin cancelam pedido.';
  end if;
  perform set_config('pieggi.compra_fn', '1', true);
  select status into v_status from public.purchase_orders where id = p_pedido for update;
  if not found then raise exception 'Pedido não encontrado.'; end if;
  if v_status in ('recebido', 'cancelado') then
    raise exception 'Pedido % não pode ser cancelado.', v_status;
  end if;

  update public.payables set status = 'cancelado',
         obs = concat_ws(' · ', obs, 'pedido cancelado')
   where purchase_order_id = p_pedido and status = 'a_pagar';
  get diagnostics v_n = row_count;

  update public.purchase_orders set status = 'cancelado', cancelado_em = now() where id = p_pedido;
  perform set_config('pieggi.compra_fn', '', true);
  return v_n;
end;
$$;

/**
 * Recebimento: grava SÓ a quantidade que chegou de cada item e passa o
 * pedido para 'recebido'. Quem está na porta da cozinha (logística,
 * produção) recebe sem ganhar update geral nos itens — preço e item de
 * pedido confirmado continuam travados. Devolve quantas divergências.
 * p_itens = [{"id": "...", "quantidade_recebida": 8}, ...]
 */
create or replace function public.compra_receber(p_pedido uuid, p_itens jsonb)
returns int
language plpgsql
security definer
set search_path = public
as $$
declare
  v_status text;
  v_dif    int;
begin
  if public.papel() not in ('admin', 'compras', 'logistica', 'producao') then
    raise exception 'Só compras, logística, produção ou admin recebem mercadoria.';
  end if;
  perform set_config('pieggi.compra_fn', '1', true);

  select status into v_status from public.purchase_orders where id = p_pedido for update;
  if not found then raise exception 'Pedido não encontrado.'; end if;
  if v_status <> 'confirmado' then
    raise exception 'Só pedido confirmado é recebido (este está %).', v_status;
  end if;

  update public.purchase_order_items i
     set quantidade_recebida = (x ->> 'quantidade_recebida')::numeric
    from jsonb_array_elements(coalesce(p_itens, '[]'::jsonb)) as x
   where i.purchase_order_id = p_pedido
     and i.id = (x ->> 'id')::uuid;

  if exists (select 1 from public.purchase_order_items
             where purchase_order_id = p_pedido and quantidade_recebida is null) then
    raise exception 'Falta conferir item. Se não veio, informe 0.';
  end if;

  update public.purchase_orders set status = 'recebido', recebido_em = now() where id = p_pedido;

  select count(*) into v_dif from public.purchase_order_items
   where purchase_order_id = p_pedido and quantidade_recebida <> quantidade;

  perform set_config('pieggi.compra_fn', '', true);
  return v_dif;
end;
$$;

/**
 * Cancela uma conta a pagar (lançamento manual ou diárias) e SOLTA as
 * diárias do título, que voltam a poder ser geradas. Feito pela tela com
 * delete direto em payable_diarias dependia da RLS e falhava calado.
 * Conta de pedido não passa por aqui: cancela-se o pedido em Compras.
 * Devolve quantas diárias foram soltas.
 */
create or replace function public.payables_cancelar(p_id uuid)
returns int
language plpgsql
security definer
set search_path = public
as $$
declare
  v_p public.payables%rowtype;
  v_n int;
begin
  if not public.pode_ver_financeiro() then
    raise exception 'Só o financeiro ou o admin cancelam conta a pagar.';
  end if;
  select * into v_p from public.payables where id = p_id for update;
  if not found then raise exception 'Conta não encontrada.'; end if;
  if v_p.status <> 'a_pagar' then
    raise exception 'Só conta a pagar em aberto é cancelada (esta está %).', v_p.status;
  end if;
  if v_p.purchase_order_id is not null then
    raise exception 'Conta de pedido: cancele o pedido em Compras.';
  end if;

  select count(*) into v_n from public.payable_diarias where payable_id = p_id;
  -- o trigger payables_solta_diarias apaga os vínculos
  update public.payables set status = 'cancelado' where id = p_id;
  return v_n;
end;
$$;

-- ------------------------------------------------------------
-- 6b. TRAVAS — a regra que mexe em dinheiro não depende da tela
-- ------------------------------------------------------------

/** Conta cancelada (por qualquer caminho) solta as diárias do título. */
create or replace function public.payables_solta_diarias()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.payable_diarias where payable_id = new.id;
  return new;
end;
$$;

drop trigger if exists payables_solta_diarias on public.payables;
create trigger payables_solta_diarias
  after update of status on public.payables
  for each row
  when (new.status = 'cancelado' and old.status is distinct from 'cancelado')
  execute function public.payables_solta_diarias();

/**
 * Pedido: 'confirmado', 'recebido' e 'cancelado' só pelas funções
 * (compra_confirmar / compra_receber / compra_cancelar), que geram ou
 * cancelam as contas a pagar. Fora delas: rascunho → enviado e nada
 * mais; pedido já confirmado só aceita mudar a observação; apagar, só
 * rascunho (o resto se cancela, e as contas não ficam órfãs).
 */
create or replace function public.purchase_orders_trava()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if coalesce(current_setting('pieggi.compra_fn', true), '') = '1' then
    return case when tg_op = 'DELETE' then old else new end;
  end if;

  if tg_op = 'DELETE' then
    if old.status <> 'rascunho' then
      raise exception 'Pedido % está %: cancele em vez de apagar.', old.numero, old.status;
    end if;
    return old;
  end if;

  if new.status is distinct from old.status
     and not (old.status = 'rascunho' and new.status = 'enviado') then
    raise exception 'Status do pedido só muda de % para % pelo botão da tela (confirmar, receber ou cancelar).',
      old.status, new.status;
  end if;

  if old.status not in ('rascunho', 'enviado')
     and (new.fornecedor_id, new.forma, new.data_prevista, new.condicao_pagamento,
          new.forma_pagamento, new.valor_total, new.numero)
         is distinct from
         (old.fornecedor_id, old.forma, old.data_prevista, old.condicao_pagamento,
          old.forma_pagamento, old.valor_total, old.numero) then
    raise exception 'Pedido % já está %: só a observação muda. Para outro valor ou prazo, cancele e faça outro.',
      old.numero, old.status;
  end if;
  return new;
end;
$$;

drop trigger if exists purchase_orders_trava on public.purchase_orders;
create trigger purchase_orders_trava
  before update or delete on public.purchase_orders
  for each row execute function public.purchase_orders_trava();

/**
 * Itens: com o pedido confirmado, recebido ou cancelado, nada muda fora
 * das funções (o recebimento grava a quantidade recebida por
 * compra_receber). Vale para o pedido de origem e o de destino.
 */
create or replace function public.purchase_order_items_trava()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_status text;
begin
  if coalesce(current_setting('pieggi.compra_fn', true), '') = '1' then
    return case when tg_op = 'DELETE' then old else new end;
  end if;

  if tg_op in ('UPDATE', 'DELETE') then
    -- no delete em cascata o pedido já sumiu: not found → deixa passar
    select status into v_status from public.purchase_orders where id = old.purchase_order_id;
    if found and v_status not in ('rascunho', 'enviado') then
      raise exception 'Pedido %: itens não mudam mais.', v_status;
    end if;
  end if;
  if tg_op in ('INSERT', 'UPDATE') then
    select status into v_status from public.purchase_orders where id = new.purchase_order_id;
    if found and v_status not in ('rascunho', 'enviado') then
      raise exception 'Pedido %: itens não mudam mais.', v_status;
    end if;
  end if;
  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

drop trigger if exists purchase_order_items_trava on public.purchase_order_items;
create trigger purchase_order_items_trava
  before insert or update or delete on public.purchase_order_items
  for each row execute function public.purchase_order_items_trava();

/**
 * Diárias presentes no período, ainda sem título → um título por
 * freelancer, com o PIX na descrição. Devolve quantos títulos criou.
 */
create or replace function public.payables_gerar_diarias(p_de date, p_ate date, p_vencimento date)
returns int
language plpgsql
security definer
set search_path = public
as $$
declare
  g       record;
  v_id    uuid;
  v_n     int := 0;
begin
  if not public.pode_ver_financeiro() then
    raise exception 'Só o financeiro ou o admin geram pagamento de diárias.';
  end if;

  for g in
    select coalesce(s.freelancer_id::text, 'nome:' || s.nome) as chave,
           s.freelancer_id,
           coalesce(min(f.nome), min(s.nome))                as nome,
           min(f.pix)                                       as pix,
           array_agg(s.id)                                  as staff_ids,
           case when count(distinct s.event_id) = 1 then min(s.event_id::text)::uuid end as event_id,
           count(*)                                         as n,
           min(s.dia)                                       as d1,
           max(s.dia)                                       as d2,
           coalesce(sum(s.valor), 0)                        as total
      from public.event_staff s
      left join public.freelancers f on f.id = s.freelancer_id
     where s.status = 'presente'
       and s.dia between p_de and p_ate
       -- diária SEM VALOR fica fora: viraria título de R$ 0 e ficaria
       -- "paga" para sempre. Continua pendente para a próxima geração.
       and s.valor is not null
       and not exists (select 1 from public.payable_diarias d where d.event_staff_id = s.id)
     group by 1, 2
  loop
    insert into public.payables
      (freelancer_id, event_id, event_staff_id, categoria, descricao, valor, vencimento, forma_pagamento, created_by)
    values
      (g.freelancer_id, g.event_id,
       case when g.n = 1 then g.staff_ids[1] end,
       'freelancer',
       format('Diárias — %s (%s diária%s, %s) · PIX: %s',
              g.nome, g.n, case when g.n > 1 then 's' else '' end,
              case when g.d1 = g.d2 then to_char(g.d1, 'DD/MM/YYYY')
                   else to_char(g.d1, 'DD/MM/YYYY') || ' a ' || to_char(g.d2, 'DD/MM/YYYY') end,
              coalesce(g.pix, 'NÃO CADASTRADO')),
       g.total, p_vencimento, 'pix', auth.uid())
    returning id into v_id;

    insert into public.payable_diarias (payable_id, event_staff_id)
    select v_id, unnest(g.staff_ids);
    v_n := v_n + 1;
  end loop;
  return v_n;
end;
$$;

