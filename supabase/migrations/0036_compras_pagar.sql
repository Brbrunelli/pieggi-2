-- ============================================================
-- 0036 — COMPRAS QUE CONVERSAM COM O FINANCEIRO
--
-- O Bruno: "fornecedor, se é cadastro pra fazer pedido, tem que estar
-- dentro de compras" e "compras e financeiro se conversam com contas a
-- pagar e receber". Esta migration fecha o circuito:
--
--   fornecedor (cadastro de compra: CNPJ, categoria, prazo, PIX)
--     → pedido de compra (rascunho → enviado → confirmado → recebido)
--       → CONFIRMAR gera as contas a pagar (parcelas pela condição)
--       → CANCELAR um confirmado cancela o que ainda não foi pago
--   diárias de freelancer presentes → um título por freelancer
--   contas a pagar + contas a receber → fluxo de caixa (na tela)
--
-- "Atrasado" e "dias até vencer" NÃO são colunas: a view calcula na hora
-- (mesmo princípio de receivables_abertos, 0022).
--
-- O que mexe em dinheiro roda no banco, não na tela: confirmar, receber
-- e cancelar pedido só pelas funções (triggers de trava na seção 6b);
-- conta cancelada solta as diárias por trigger; diária sem valor não
-- entra em título.
--
-- Idempotente: pode rodar de novo sem erro.
-- ============================================================

-- ------------------------------------------------------------
-- 1. QUEM VÊ E QUEM PEDE
-- ------------------------------------------------------------
/** módulo Compras (lista, pedidos, fornecedores): espelho de verCompras */
create or replace function public.pode_ver_compras()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.papel() in ('admin', 'compras', 'financeiro', 'logistica');
$$;

/** fazer pedido de compra (vira conta a pagar): espelho de pedirCompra */
create or replace function public.pode_pedir_compra()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.papel() in ('admin', 'compras');
$$;

