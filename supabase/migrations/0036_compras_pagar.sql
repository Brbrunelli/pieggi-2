alter table public.fornecedores
  add column if not exists cnpj               text,
  add column if not exists categoria          text,
  add column if not exists condicao_pagamento text,
  add column if not exists forma_pagamento    text,
  add column if not exists pix                text;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'fornecedores_categoria_check') then
    alter table public.fornecedores add constraint fornecedores_categoria_check
      check (categoria is null or categoria in
        ('hortifruti', 'salgados', 'frios', 'bebidas', 'descartaveis', 'embalagens', 'outros'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'fornecedores_forma_pagamento_check') then
    alter table public.fornecedores add constraint fornecedores_forma_pagamento_check
      check (forma_pagamento is null or forma_pagamento in ('pix', 'boleto', 'transferencia'));
  end if;
end $$;

-- compras também cadastra fornecedor (antes só a logística — 0033)
drop policy if exists "fornecedores_insert" on public.fornecedores;
