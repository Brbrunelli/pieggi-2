create policy "fornecedores_insert" on public.fornecedores for insert to authenticated
  with check (public.pode_escalar() or public.pode_pedir_compra());
create policy "fornecedores_update" on public.fornecedores for update to authenticated
  using (public.pode_escalar() or public.pode_pedir_compra())
  with check (public.pode_escalar() or public.pode_pedir_compra());

-- ------------------------------------------------------------
-- 3. PEDIDO DE COMPRA
-- ------------------------------------------------------------
create table if not exists public.purchase_orders (
  id                 uuid primary key default gen_random_uuid(),
  /** número legível ("pedido 12") — é o que se fala com o fornecedor */
  numero             bigint generated by default as identity unique,
  fornecedor_id      uuid not null references public.fornecedores (id),
  status             text not null default 'rascunho'
                     check (status in ('rascunho', 'enviado', 'confirmado', 'recebido', 'cancelado')),
  forma              text not null default 'entrega' check (forma in ('retirada', 'entrega')),
  data_prevista      date,
  /** 'avista' | '7' | '14' | '21' | '28' | '14/28' (dias a partir da data prevista) */
  condicao_pagamento text not null default 'avista',
  forma_pagamento    text check (forma_pagamento is null or forma_pagamento in ('pix', 'boleto', 'transferencia')),
  /** soma dos itens — recalculada pela função de confirmação */
  valor_total        numeric(12,2) not null default 0,
  obs                text,
  criado_por         uuid references public.profiles (id),
  enviado_em         timestamptz,
  confirmado_em      timestamptz,
  recebido_em        timestamptz,
  cancelado_em       timestamptz,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);

create index if not exists purchase_orders_status_idx on public.purchase_orders (status, data_prevista);
create index if not exists purchase_orders_forn_idx on public.purchase_orders (fornecedor_id);

drop trigger if exists on_purchase_order_update on public.purchase_orders;
create trigger on_purchase_order_update
  before update on public.purchase_orders
  for each row execute function public.touch_updated_at();

create table if not exists public.purchase_order_items (
  id                  uuid primary key default gen_random_uuid(),
  purchase_order_id   uuid not null references public.purchase_orders (id) on delete cascade,
  descricao           text not null,
  quantidade          numeric(12,3) not null default 0,
  unidade             text not null default 'un',
  /** em branco até o fornecedor passar o preço — sem preço não confirma */
  preco_unitario      numeric(12,4),
  /** de qual evento é o item (custo no resultado por evento) */
  event_id            uuid references public.events (id) on delete set null,
  /** conferência no recebimento; diferente da quantidade = divergência */
  quantidade_recebida numeric(12,3),
  ordem               int not null default 0,
  created_at          timestamptz not null default now()
);

create index if not exists purchase_order_items_po_idx on public.purchase_order_items (purchase_order_id);
create index if not exists purchase_order_items_event_idx on public.purchase_order_items (event_id);

-- ------------------------------------------------------------
-- 4. CONTAS A PAGAR
-- ------------------------------------------------------------
create table if not exists public.payables (
  id                uuid primary key default gen_random_uuid(),
  fornecedor_id     uuid references public.fornecedores (id) on delete set null,
  purchase_order_id uuid references public.purchase_orders (id) on delete set null,
  event_staff_id    uuid references public.event_staff (id) on delete set null,
  freelancer_id     uuid references public.freelancers (id) on delete set null,
  event_id          uuid references public.events (id) on delete set null,
  categoria         text not null default 'outros'
                    check (categoria in ('insumos', 'freelancer', 'transporte', 'aluguel', 'impostos', 'outros')),
  descricao         text not null,
  parcela           int not null default 1,
  parcelas          int not null default 1,
  valor             numeric(12,2) not null,
  vencimento        date not null,
  status            text not null default 'a_pagar' check (status in ('a_pagar', 'pago', 'cancelado')),
  valor_pago        numeric(12,2),
  pago_em           date,
  forma_pagamento   text,
  obs               text,
  created_by        uuid references public.profiles (id),
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

create index if not exists payables_venc_idx on public.payables (status, vencimento);
create index if not exists payables_po_idx on public.payables (purchase_order_id);
create index if not exists payables_event_idx on public.payables (event_id);

drop trigger if exists on_payable_update on public.payables;
create trigger on_payable_update
  before update on public.payables
  for each row execute function public.touch_updated_at();

-- Quais diárias já viraram título. Um título junta várias diárias do
-- mesmo freelancer; o unique impede pagar a mesma diária duas vezes.
create table if not exists public.payable_diarias (
  payable_id     uuid not null references public.payables (id) on delete cascade,
  event_staff_id uuid not null unique references public.event_staff (id) on delete cascade,
  primary key (payable_id, event_staff_id)
);

